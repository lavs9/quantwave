"""quantwave.datasets — zero-network OHLCV data layer.

Canonical OHLCV schema
-----------------------
Every frame produced or consumed by this module conforms to a single
canonical schema (see ``SCHEMA`` below):

    ts       Datetime(time_unit="us", time_zone="Asia/Kolkata")   tz-aware timestamp (IST)
    open     Float64
    high     Float64
    low      Float64
    close    Float64
    volume   Float64
    symbol   Utf8   (optional — present for multi-symbol frames)

Rows are sorted by ``ts`` in strictly monotonic non-decreasing order
(per symbol, when ``symbol`` is present). Timestamps are always timezone
aware and expressed in Asia/Kolkata (IST), per this project's convention.

Two entry points cover the zero-network path:

``synthetic(...)``
    A deterministic OHLCV generator: geometric Brownian motion (GBM) drift
    with volatility-regime switches, plus a simple volume model correlated
    with absolute returns. The same ``seed`` always produces a byte-identical
    frame. This aligns with (and is loosely modeled on) the synthetic
    generator in ``benchmarks/data.py`` (``generate_ohlcv`` / ``OhlcvConfig``
    / ``frame_hash``), which the benchmark harness uses for latency/perf
    self-tests. ``datasets.synthetic`` is the "real" OHLC/regime-aware
    generator; ``benchmarks.data.generate_ohlcv`` remains a lighter-weight
    variant tuned for benchmark throughput and is left untouched.

``load_sample()``
    Returns a small (~1-2MB), bundled, **synthetic** sample shipped with the
    package as a parquet file. It is generated by this module's own
    ``synthetic()`` function (see ``quantwave/_generate_sample.py`` in this
    package's source tree, or the docstring on ``load_sample`` for the exact
    recipe) — it is NOT real exchange data. Real NSE/exchange market data
    almost certainly cannot be redistributed under most vendor terms of
    service, so nothing scraped or sourced from a real exchange is bundled
    or committed to this repository.

Fetchers (``quantwave.data``) for pulling *real* market data (yfinance, NSE
bhavcopy, NSE option chain) live in the sibling ``quantwave.data`` module and
are documented there; they are optional, lazily-imported, and out of scope
for this module's zero-network guarantees.
"""

from __future__ import annotations

import hashlib
from datetime import datetime, timedelta
from typing import Mapping, Sequence

import numpy as np
import polars as pl

IST = "Asia/Kolkata"

#: Canonical OHLCV schema: column name -> polars dtype. ``symbol`` is optional
#: (only required when a frame carries more than one instrument) but is part
#: of the contract whenever present, so it is included here for documentation;
#: callers that only ever build a single-symbol frame may omit it.
SCHEMA: Mapping[str, pl.DataType] = {
    "ts": pl.Datetime(time_unit="us", time_zone=IST),
    "open": pl.Float64,
    "high": pl.Float64,
    "low": pl.Float64,
    "close": pl.Float64,
    "volume": pl.Float64,
    "symbol": pl.Utf8,
}

_DATA_DIR = __import__("pathlib").Path(__file__).resolve().parent / "data"
_SAMPLE_PATH = _DATA_DIR / "sample.parquet"

_DEFAULT_START = datetime(2015, 1, 1, 9, 15)


def frame_hash(df: pl.DataFrame) -> str:
    """Stable sha256 hash of a canonical-schema frame's numeric + symbol data.

    Mirrors ``benchmarks.data.frame_hash`` but also folds in ``ts`` (as
    integer microseconds) and ``symbol`` (when present) so that determinism
    tests over full canonical frames are sensitive to every column.
    """
    parts: list[bytes] = []
    if "ts" in df.columns:
        parts.append(df["ts"].to_physical().to_numpy().tobytes())
    for col in ("open", "high", "low", "close", "volume"):
        if col in df.columns:
            parts.append(df[col].to_numpy().tobytes())
    if "symbol" in df.columns:
        parts.append("\x1f".join(df["symbol"].to_list()).encode("utf-8"))
    return hashlib.sha256(b"".join(parts)).hexdigest()


def _generate_one_symbol(
    rng: np.random.Generator,
    rows: int,
    start: datetime,
    freq: timedelta,
    n_regimes: int,
    base_price: float,
) -> pl.DataFrame:
    """GBM-with-regime-switching-volatility path for a single instrument.

    - Volatility regimes: ``rows`` is split into ``n_regimes`` contiguous
      segments; each segment draws its own annualized-vol multiplier from a
      log-uniform range, so regimes have visibly different variance.
    - Drift: a small constant per-bar drift plus regime-level drift noise.
    - Volume: lognormal base volume, scaled up on bars with large absolute
      returns (volume-follows-volatility), fully deterministic given ``rng``.
    """
    # Split rows into n_regimes contiguous segments (last gets the remainder).
    n_regimes = max(1, min(n_regimes, rows))
    bounds = np.linspace(0, rows, n_regimes + 1, dtype=int)

    log_ret = np.empty(rows, dtype=np.float64)
    regime_vol = np.empty(rows, dtype=np.float64)
    for i in range(n_regimes):
        lo, hi = bounds[i], bounds[i + 1]
        seg_len = hi - lo
        if seg_len <= 0:
            continue
        # Log-uniform vol multiplier -> regimes differ by up to ~8x in stdev.
        vol = float(rng.uniform(0.15, 1.2))
        drift = float(rng.normal(0.0002, 0.0004))
        sigma = vol * 0.01  # per-bar stdev in log-return space
        seg = rng.normal(loc=drift, scale=sigma, size=seg_len)
        log_ret[lo:hi] = seg
        regime_vol[lo:hi] = sigma

    log_price = np.log(base_price) + np.cumsum(log_ret)
    close = np.exp(log_price)

    # Intrabar high/low/open derived from close + a regime-scaled intrabar range.
    intrabar_noise = rng.uniform(0.2, 1.0, rows) * regime_vol * close
    open_shift = rng.normal(0.0, 1.0, rows) * regime_vol * close * 0.5
    open_ = close + open_shift
    high = np.maximum(open_, close) + intrabar_noise
    low = np.minimum(open_, close) - intrabar_noise
    low = np.maximum(low, 0.01)  # keep prices positive

    # Volume model: lognormal base, amplified by |return| (volume-vol link).
    abs_ret = np.abs(log_ret)
    base_vol = rng.lognormal(mean=11.5, sigma=0.5, size=rows)  # ~ tens of thousands
    volume = base_vol * (1.0 + 8.0 * abs_ret / (abs_ret.mean() + 1e-9))
    volume = np.round(volume).astype(np.float64)

    ts = [start + i * freq for i in range(rows)]

    return pl.DataFrame(
        {
            "ts": pl.Series("ts", ts, dtype=pl.Datetime(time_unit="us")).dt.replace_time_zone(IST),
            "open": open_.astype(np.float64),
            "high": high.astype(np.float64),
            "low": low.astype(np.float64),
            "close": close.astype(np.float64),
            "volume": volume,
        }
    )


def synthetic(
    seed: int,
    rows: int = 10_000,
    start: datetime | None = None,
    freq: timedelta | str = "1d",
    symbols: Sequence[str] | None = None,
    n_regimes: int = 3,
    base_price: float = 1000.0,
) -> pl.DataFrame:
    """Deterministic synthetic OHLCV generator (GBM + volatility regimes + volume).

    Same ``seed`` always yields a byte-identical frame (see ``frame_hash``).
    Volatility regimes are contiguous segments of the run, each with its own
    (log-uniform) vol multiplier, so variance visibly differs across regimes.

    Parameters
    ----------
    seed:
        Master seed. Deterministic: same seed -> identical output frame.
    rows:
        Number of bars to generate per symbol.
    start:
        First bar timestamp (naive; interpreted as IST wall-clock). Defaults
        to 2015-01-01 09:15 (NSE cash market open convention).
    freq:
        Bar spacing: a ``timedelta``, or one of the shorthand strings
        ``"1d"``, ``"1min"``/``"1m"``, ``"5min"``/``"5m"``, ``"1h"``.
    symbols:
        Optional sequence of symbol names. When given, one independent
        (but seed-derived, deterministic) path is generated per symbol and
        the result is the row-wise concatenation, with a ``symbol`` column.
        When omitted, a single unlabeled path is returned (no ``symbol``
        column).
    n_regimes:
        Number of volatility regimes to split the run into.
    base_price:
        Starting price level for the GBM path.

    Returns
    -------
    pl.DataFrame in the canonical schema (``SCHEMA``), sorted by ``ts``
    (per symbol, if present).
    """
    if rows <= 0:
        raise ValueError("rows must be positive")
    if isinstance(freq, str):
        freq = _parse_freq(freq)
    start = start or _DEFAULT_START

    if not symbols:
        rng = np.random.default_rng(seed)
        df = _generate_one_symbol(rng, rows, start, freq, n_regimes, base_price)
        return df.select(["ts", "open", "high", "low", "close", "volume"])

    frames = []
    for i, sym in enumerate(symbols):
        # Derive a distinct-but-deterministic sub-seed per symbol.
        sub_seed = (int(seed) * 1_000_003 + i * 7919 + hash(sym) % 104_729) & 0xFFFFFFFF
        rng = np.random.default_rng(sub_seed)
        sym_price = base_price * float(1.0 + 0.15 * i)
        df = _generate_one_symbol(rng, rows, start, freq, n_regimes, sym_price)
        df = df.with_columns(pl.lit(sym).alias("symbol"))
        frames.append(df)
    out = pl.concat(frames, how="vertical")
    return out.select(["ts", "open", "high", "low", "close", "volume", "symbol"])


def _parse_freq(freq: str) -> timedelta:
    freq = freq.strip().lower()
    table = {
        "1d": timedelta(days=1),
        "1day": timedelta(days=1),
        "1min": timedelta(minutes=1),
        "1m": timedelta(minutes=1),
        "5min": timedelta(minutes=5),
        "5m": timedelta(minutes=5),
        "15min": timedelta(minutes=15),
        "15m": timedelta(minutes=15),
        "1h": timedelta(hours=1),
        "1hour": timedelta(hours=1),
    }
    if freq not in table:
        raise ValueError(f"Unsupported freq shorthand: {freq!r} (use a timedelta instead)")
    return table[freq]


def load_sample() -> pl.DataFrame:
    """Return the bundled sample OHLCV dataset (offline, zero network).

    The returned frame is **synthetic** — it is NOT real NSE/exchange data.
    Real market data generally cannot be redistributed under exchange/vendor
    terms of service, so this package ships a calibrated synthetic sample
    instead: a NIFTY-like index plus two stock-like instruments, daily bars
    over roughly 10 years, generated deterministically via this module's own
    ``synthetic()`` function (seed=1337, n_regimes=5) and saved to
    ``quantwave/data/sample.parquet``. See this package's
    ``quantwave/_generate_sample.py`` for the exact generation recipe used to
    produce the committed parquet file (regenerate with
    ``python -m quantwave._generate_sample``).

    Returns
    -------
    pl.DataFrame in the canonical schema (``SCHEMA``), sorted by ``ts``
    per symbol.
    """
    if not _SAMPLE_PATH.exists():
        raise FileNotFoundError(
            f"Bundled sample not found at {_SAMPLE_PATH}. This is a packaging "
            "bug — the parquet should ship inside quantwave/data/."
        )
    return pl.read_parquet(_SAMPLE_PATH)
